/**
 * Bundle one regression run into a single human-readable Markdown file:
 * executive summary + audits + progression-discipline finding + qualitative
 * evaluator scores + every transcript, in scenario order.
 *
 * Run:  node eval/compile-report.mjs [eval-results/run_<id>]
 * Out:  <run>/FULL_REPORT.md
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { PROGRESS_RANK } from '../scripts/engine-bundle.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

let runDir = process.argv[2];
if (!runDir) {
  const base = path.join(ROOT, 'eval-results');
  const runs = readdirSync(base).filter((d) => d.startsWith('run_')).sort();
  runDir = path.join(base, runs[runs.length - 1]);
} else if (!path.isAbsolute(runDir)) {
  runDir = path.join(ROOT, runDir);
}
const read = (f) => (existsSync(path.join(runDir, f)) ? readFileSync(path.join(runDir, f), 'utf8') : null);

// Canonical scenario order (falls back to alphabetical if the library is missing).
let order = [];
try {
  order = JSON.parse(readFileSync(path.join(ROOT, 'eval/scenarios.json'), 'utf8')).map((s) => s.scenario_id);
} catch {}

// Progression-discipline audit (brief §14.7): stage jumps > 1 in a single user turn.
const logsDir = path.join(runDir, 'logs');
const jumps = [];
if (existsSync(logsDir)) {
  for (const f of readdirSync(logsDir).filter((x) => x.endsWith('.json'))) {
    const log = JSON.parse(readFileSync(path.join(logsDir, f), 'utf8'));
    for (const t of log.turns ?? []) {
      const d = t.stage_before && t.stage_after ? PROGRESS_RANK[t.stage_after] - PROGRESS_RANK[t.stage_before] : 0;
      if (d > 1) {
        // "premature" = a deep stage (rooted+) entered without a prior first shape — the
        // unearned jump the brief flags. An earned unseen->first_shape is not premature.
        const premature = PROGRESS_RANK[t.stage_after] >= PROGRESS_RANK.rooted && PROGRESS_RANK[t.stage_before] < PROGRESS_RANK.first_shape;
        jumps.push({ scenario: log.scenario_id, turn: t.index, from: t.stage_before, to: t.stage_after, delta: d, premature, label_source: t.label_source ?? null, intent: t.intent ?? null });
      }
    }
  }
}

const out = [];
out.push(`# Scimagotchi conversation-engine regression — FULL REPORT`, '');
out.push(`Run: \`${path.basename(runDir)}\``, '');
out.push('This single file bundles the executive summary, the unlock / safety / memory audits, the progression-discipline finding, the qualitative evaluator scores, and every conversation transcript. Generated by `eval/compile-report.mjs`.', '');
out.push('---', '');

const summary = read('summary.md');
if (summary) out.push(summary, '', '---', '');

// Progression discipline section
out.push('## Progression discipline audit (brief §14.7)', '');
const premature = jumps.filter((j) => j.premature);
out.push(
  'Stages the engine advanced by more than one level in a single turn. **Premature** = a deep stage (rooted+) entered with no prior first shape — the unearned jump the brief flags. An earned `unseen→first_shape` (label + anchor in one rich turn) is expected and not premature.',
  '',
);
out.push(`**Premature deep jumps: ${premature.length}.**  (Total >1-level transitions, incl. earned first shapes: ${jumps.length}.)`, '');
if (jumps.length) {
  out.push('| Scenario | Turn | From → To | Δ | Premature | Label source | Intent |', '|---|---|---|---|---|---|---|');
  for (const j of jumps.sort((a, b) => Number(b.premature) - Number(a.premature) || b.delta - a.delta))
    out.push(`| ${j.scenario} | ${j.turn} | ${j.from} → ${j.to} | +${j.delta} | ${j.premature ? '**YES**' : 'no'} | ${j.label_source ?? ''} | ${j.intent ?? ''} |`);
  out.push('');
}
out.push('---', '');

const scores = read('scores.md');
if (scores) out.push(scores, '', '---', '');

// Transcripts, in scenario order
out.push('# Appendix — full transcripts', '');
const tDir = path.join(runDir, 'transcripts');
const files = existsSync(tDir) ? readdirSync(tDir).filter((f) => f.endsWith('.md')) : [];
const sorted = files.sort((a, b) => {
  const ia = order.indexOf(a.replace(/\.md$/, ''));
  const ib = order.indexOf(b.replace(/\.md$/, ''));
  return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib);
});
for (const f of sorted) {
  out.push(readFileSync(path.join(tDir, f), 'utf8'), '', '---', '');
}

const outPath = path.join(runDir, 'FULL_REPORT.md');
writeFileSync(outPath, out.join('\n'));
console.log(`[compile] wrote ${path.relative(ROOT, outPath)} (${files.length} transcripts, ${jumps.length} stage-jump rows)`);
