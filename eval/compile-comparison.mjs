/**
 * Bundle a multi-model benchmark folder into one human-readable Markdown file:
 * the cross-model COMPARISON.md, each model's qualitative judgement (scores.md),
 * and every transcript grouped BY SCENARIO with all models side-by-side (so the
 * identical-input comparison is easy to read), each with its per-turn engine
 * decisions and that model's evaluator verdict.
 *
 * Run:  node eval/compile-comparison.mjs [eval-results/models_<id>]
 * Out:  <folder>/FULL_REPORT.md
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
let runDir = process.argv[2];
if (!runDir) {
  const base = path.join(ROOT, 'eval-results');
  const runs = readdirSync(base).filter((d) => d.startsWith('models_')).sort();
  if (!runs.length) { console.error('no models_* folder found'); process.exit(1); }
  runDir = path.join(base, runs[runs.length - 1]);
} else if (!path.isAbsolute(runDir)) {
  runDir = path.join(ROOT, runDir);
}
const manifest = JSON.parse(readFileSync(path.join(runDir, 'manifest.json'), 'utf8'));
const MODELS = manifest.models;
const read = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);

// Scenario order (fixed set, then regression set) + hidden truth.
const order = [];
for (const m of manifest.modes) {
  let scns = [];
  try { scns = JSON.parse(readFileSync(path.join(ROOT, m.file), 'utf8')); } catch {}
  for (const s of scns) order.push({ mode: m.mode, id: s.scenario_id, hidden: s.hidden_truth, condition: s.target_condition });
}

// Per-model evaluator verdicts, keyed by scenario_id.
const evalsByModel = {};
for (const model of MODELS) {
  const e = read(path.join(runDir, model, 'evaluations.json'));
  evalsByModel[model] = e ? Object.fromEntries(JSON.parse(e).map((x) => [x.scenario_id, x])) : {};
}

function verdictLine(ev) {
  if (!ev) return '_(not judged)_';
  if (ev.error) return `_evaluator error: ${ev.error}_`;
  const mo = (ev.micro_overclaims ?? []).filter((x) => x && x.quote);
  const sev = mo.filter((x) => x.severity === 'serious' || x.severity === 'moderate').length;
  const bits = [`EL ${ev.scores?.earned_learning ?? '?'}/5`, `micro-overclaims ${mo.length}${sev ? ` (${sev} mod+)` : ''}`];
  if (ev.doorway) bits.push(`doorway: ${ev.doorway}`);
  if (ev.scores) bits.push(`mean ${(Object.values(ev.scores).reduce((a, b) => a + b, 0) / Object.values(ev.scores).length).toFixed(1)}`);
  let s = `> ${bits.join(' · ')}`;
  if (mo.length) s += '\n> micro-overclaims: ' + mo.map((x) => `[${x.severity ?? '?'}/${x.source ?? '?'}] "${x.quote}"`).join(' · ');
  if (ev.failure_tags?.length) s += `\n> tags: ${ev.failure_tags.join(', ')}`;
  if (ev.biggest_issue) s += `\n> biggest issue: ${ev.biggest_issue}`;
  return s;
}

function modelBlock(model, sc) {
  const key = `${sc.mode}__${sc.id}`;
  const logRaw = read(path.join(runDir, model, 'logs', `${key}.json`));
  if (!logRaw) return `#### ${model}\n_(no log)_\n`;
  const log = JSON.parse(logRaw);
  const lines = [`#### ${model}`, verdictLine(evalsByModel[model][sc.id]), ''];
  for (const m of log.transcript) {
    if (m.speaker === 'user') lines.push(`**User${m.action_intent ? ` [tap: ${m.action_intent}]` : ''}:** ${m.text}`);
    else if (m.speaker === 'assistant') lines.push(`**Companion:** ${m.text}`);
    else lines.push(`_${m.text}_`);
  }
  lines.push('');
  const dec = log.turns
    .filter((t) => !t.safety && t.reply !== undefined)
    .map(
      (t) => `\`${t.stage}\` ${t.stage_before}→${t.stage_after}${t.unlocked ? ' UNLOCK' : ''}${t.modal ? ` MODAL:${t.modal}` : ''}${t.shade ? ` shade=${t.shade}(${t.shade_source})` : ''}`,
    );
  if (dec.length) lines.push('_engine:_ ' + dec.join(' · '));
  lines.push('');
  return lines.join('\n');
}

const out = [];
out.push('# Scimagotchi model benchmark — full report', '');
out.push(`Run: \`${path.basename(runDir)}\`  ·  Models: ${MODELS.join(', ')}`, '');
out.push('Contains: the cross-model comparison + decision framework, each model\'s qualitative judgement, and every transcript grouped by scenario (all models side-by-side, identical inputs). Generated by `eval/compile-comparison.mjs`.', '');
out.push('---', '');

const comparison = read(path.join(runDir, 'COMPARISON.md'));
if (comparison) out.push(comparison, '', '---', '');

out.push('# Qualitative judgement per model', '');
out.push('_(Same evaluator judged every model. Full per-scenario verdicts.)_', '');
for (const model of MODELS) {
  const sc = read(path.join(runDir, model, 'scores.md'));
  out.push(`## ${model}`, '');
  out.push(sc ? sc.replace(/^# .*$/m, '').trim() : '_(not judged)_', '');
  out.push('---', '');
}

out.push('# Appendix — transcripts by scenario (all models, identical inputs)', '');
for (const sc of order) {
  out.push(`## [${sc.mode}] ${sc.id}`, '');
  if (sc.hidden) out.push(`*Hidden truth:* ${sc.hidden}`, '');
  for (const model of MODELS) out.push(modelBlock(model, sc));
  out.push('---', '');
}

const outPath = path.join(runDir, 'FULL_REPORT.md');
writeFileSync(outPath, out.join('\n'));
console.log(`[compile] wrote ${path.relative(ROOT, outPath)} (${order.length} scenarios × ${MODELS.length} models)`);
